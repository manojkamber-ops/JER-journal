        "Artificial intelligence (AI) has moved from a speculative research agenda to an operational necessity for young firms that must compete with limited resources against incumbents with deep pockets. Schumpeter (1934) characterised entrepreneurship as a process of creative destruction in which new combinations of technology and resources displace older production functions; AI represents precisely such a general-purpose recombination, capable of lowering the cost of prediction, personalisation and coordination at scale (Agrawal, Gans, & Goldfarb, 2018). Brynjolfsson and McAfee (2014) argued that digital technologies compound the productive capacity of firms while eroding the advantages of scale, and subsequent firm-level evidence has confirmed that generative AI can raise worker and firm productivity by double-digit margins (Brynjolfsson, Li, & Raymond, 2025). For start-ups, whose defining constraint is resource scarcity, the capacity to substitute intelligent software for labour, capital and time is therefore not a peripheral efficiency question but a core strategic capability (Csaszar & Steinberger, 2022).",
        "India provides a compelling laboratory for studying these dynamics. The country hosts more than 1.57 lakh DPIIT-recognised start-ups that have collectively created over 1.66 million jobs, and its AI market is projected to expand at a compound annual growth rate of 25 to 35 per cent to reach approximately USD 17 billion by 2027 (Ministry of Finance, 2025; NASSCOM, 2023). National policy has reinforced this momentum: the National Strategy for Artificial Intelligence articulates an #AIforAll vision (NITI Aayog, 2018), and the IndiaAI Mission, approved in March 2024, commits more than Rs. 10,300 crore over five years to compute capacity, data platforms and skilling. NITI Aayog estimates that AI could add USD 957 billion to India's economy by 2035, and management research increasingly frames AI as a source of business value that must be aligned with organisational routines to be realised (Enholm, Papagiannidis, Mikalef, & Krogstie, 2022).",
