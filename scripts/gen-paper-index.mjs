// Regenerates src/data/papers/index.ts from the files in src/data/papers/.
// Files exporting `paper` are complete PaperSpecs; files exporting `fulltext` add full text to an
// article already defined in journal.ts. Run: node scripts/gen-paper-index.mjs
import { readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "papers");
const papers = [];
const fulltexts = [];
for (const file of readdirSync(dir).sort()) {
  if (!/^\d{4}-v\d+-i\d+-[\w-]+\.ts$/.test(file)) continue;
  const src = readFileSync(join(dir, file), "utf8");
  const mod = file.replace(/\.ts$/, "");
  if (/export const paper\b/.test(src)) papers.push(mod);
  else if (/export const fulltext\b/.test(src)) fulltexts.push(mod);
}
const ident = (m) => "p_" + m.replace(/-/g, "_");
const out = [
  "// GENERATED by scripts/gen-paper-index.mjs — do not edit by hand.",
  'import type { FulltextSpec, PaperSpec } from "../paper-spec";',
  ...papers.map((m) => `import { paper as ${ident(m)} } from "./${m}";`),
  ...fulltexts.map((m) => `import { fulltext as ${ident(m)} } from "./${m}";`),
  "",
  `export const ALL_PAPERS: PaperSpec[] = [${papers.map(ident).join(", ")}];`,
  "",
  `export const ALL_FULLTEXTS: FulltextSpec[] = [${fulltexts.map(ident).join(", ")}];`,
  "",
].join("\n");
const tmp = join(dir, `.index.${process.pid}.tmp`);
writeFileSync(tmp, out);
renameSync(tmp, join(dir, "index.ts"));
console.log(`papers/index.ts: ${papers.length} papers, ${fulltexts.length} full texts`);
